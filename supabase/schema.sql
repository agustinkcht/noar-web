-- Perfil del cliente (nombre y teléfono para coordinar la entrega).
create table if not exists public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre text,
  telefono text,
  actualizado timestamptz not null default now()
);

-- Quiénes ven y gestionan todos los pedidos.
create table if not exists public.admins (
  email text primary key
);
insert into public.admins (email) values ('agustinkcht@gmail.com') on conflict do nothing;

create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where email = (auth.jwt() ->> 'email'));
$$;

create table if not exists public.pedidos (
  id uuid primary key default gen_random_uuid(),            -- va en el link: /pedido/?id=…
  numero bigint generated by default as identity (start with 1001) unique,
  user_id uuid not null default auth.uid() references auth.users (id),
  email text,
  nombre text,
  telefono text,
  items jsonb not null,          -- [{slug, variant, desl, nombre, foto, cantidad, unitario, subtotal}]
  subtotal integer not null,
  envio jsonb,                   -- {tipo, direccion, lugar, zona, precio, cobro, nota}
  envio_cobro integer,           -- null = a cotizar
  total integer not null,
  nota text,
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'confirmado', 'concretado', 'cancelado')),
  creado timestamptz not null default now(),
  actualizado timestamptz not null default now()
);
create index if not exists pedidos_user_idx on public.pedidos (user_id, creado desc);

alter table public.perfiles enable row level security;
alter table public.pedidos enable row level security;
alter table public.admins enable row level security;

-- Perfiles: cada uno el suyo; el admin ve todos.
drop policy if exists "perfil propio" on public.perfiles;
create policy "perfil propio" on public.perfiles
  for all using (id = auth.uid() or public.es_admin())
  with check (id = auth.uid());

-- Pedidos: el cliente ve los suyos y el admin todos.
drop policy if exists "ver pedidos" on public.pedidos;
create policy "ver pedidos" on public.pedidos
  for select using (user_id = auth.uid() or public.es_admin());

drop policy if exists "crear pedido" on public.pedidos;
create policy "crear pedido" on public.pedidos
  for insert with check (user_id = auth.uid() and estado = 'pendiente');

-- El cliente solo puede cancelar su pedido mientras está pendiente; el admin cambia lo que quiera.
drop policy if exists "cliente cancela" on public.pedidos;
create policy "cliente cancela" on public.pedidos
  for update using (user_id = auth.uid() and estado = 'pendiente')
  with check (user_id = auth.uid() and estado in ('pendiente', 'cancelado'));

drop policy if exists "admin gestiona" on public.pedidos;
create policy "admin gestiona" on public.pedidos
  for update using (public.es_admin()) with check (public.es_admin());

create or replace function public.tocar_actualizado() returns trigger
language plpgsql as $$ begin new.actualizado = now(); return new; end $$;
drop trigger if exists pedidos_actualizado on public.pedidos;
create trigger pedidos_actualizado before update on public.pedidos
  for each row execute function public.tocar_actualizado();
